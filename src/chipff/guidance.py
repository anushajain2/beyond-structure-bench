"""Per-material model guidance: which model can be relied on for which material.

For every material and model, each property is graded against experiment with the thresholds fixed before any
result was seen (configs/benchmark.yaml `thresholds`). A plain verdict follows from the grades alone:

  reliable          every graded property is good
  usable            nothing is poor
  avoid for <X>     property X is poor (thermal expansion at 300 K or over the window, bulk modulus, lattice)
  avoid: <failure>  the model failed outright (changed the crystal form, unstable crystal, unstable elastic tensor)
  not graded        no property could be graded
  ... ; heat untested   no thermal-expansion grade exists (no reference, layered, or the model failed)

The verdict summarises this benchmark's evidence for that material; it is not a guarantee for other properties.
"""

from __future__ import annotations

import math

import pandas as pd

PROPS = [  # (column label, table key, error column, exclusion column, threshold key)
    ("lattice", "lat", "err_lin_exp_pct", "excluded", "lattice"),
    ("bulk modulus", "bulk", "err_exp_pct", "excluded", "bulk_modulus"),
    ("expansion at 300 K", "therm", "err_300K_pct", "excluded_300K", "thermal_expansion"),
    ("expansion over the window", "therm", "err_exp_pct", "excluded", "thermal_expansion"),
]


def _grade(err, th):
    if err is None or (isinstance(err, float) and math.isnan(err)):
        return None
    a = abs(err)
    return "good" if a <= th["good"] else "okay" if a <= th["okay"] else "poor"


def model_guidance(lat: pd.DataFrame, bulk: pd.DataFrame, therm: pd.DataFrame, thresholds: dict,
                   model_failures: tuple[str, ...]) -> pd.DataFrame:
    """One row per material x model: each property's grade and error, the reason where ungraded, and the verdict.
    `model_failures` are the exclusion reasons that count against the model (chipff.analysis.MODEL_FAILURES)."""
    tables = {"lat": lat, "bulk": bulk, "therm": therm}
    idx = {k: t.set_index(["model", "material"]) for k, t in tables.items() if not t.empty}
    rows = []
    for (mk, mat), r in idx["lat"].iterrows():
        row = {"material": mat, "class": r["class"], "model": mk}
        poor, failed, graded_heat = [], [], False
        for label, key, col, exc, thk in PROPS:
            t = idx.get(key)
            rec = t.loc[(mk, mat)] if t is not None and (mk, mat) in t.index else None
            err = None if rec is None else rec.get(col)
            g = _grade(err, thresholds[thk])
            row[f"{label}: grade"] = g
            row[f"{label}: error %"] = None if g is None else round(float(err), 1)
            if g is None:
                why = None if rec is None else rec.get(exc)
                why = why if isinstance(why, str) and why else "no experimental reference"
                row[f"{label}: why not graded"] = why
                if why.startswith(model_failures):
                    failed.append(why.split(" (")[0])
            if g == "poor":
                poor.append(label)
            if g and label.startswith("expansion"):
                graded_heat = True
        grades = [row[f"{p[0]}: grade"] for p in PROPS if row[f"{p[0]}: grade"]]
        if failed:
            verdict = "avoid: " + ", ".join(dict.fromkeys(failed))
        elif poor:
            verdict = "avoid for " + ", ".join(poor)
        elif not grades:
            verdict = "not graded"
        elif all(g == "good" for g in grades):
            verdict = "reliable"
        else:
            verdict = "usable"
        if not graded_heat and not failed and grades:
            verdict += "; heat untested"
        row["verdict"] = verdict
        rows.append(row)
    return pd.DataFrame(rows).sort_values(["class", "material", "model"]).reset_index(drop=True)


def guidance_markdown(g: pd.DataFrame, labels: dict[str, str], class_labels: dict[str, str]) -> str:
    """docs/model_guidance.md: one table per material class, rows = materials, columns = models."""
    models = list(dict.fromkeys(g["model"]))
    out = ["# Which model can I rely on for my material?",
           "",
           "*Generated by `chipff analyze` from `results/model_guidance.csv`; do not edit by hand.*",
           "",
           "Each cell is one model's verdict for one material, from its grades against laboratory measurements on the",
           "benchmark's three properties. The grades use the thresholds fixed before any result was seen: lattice",
           "constant good within 1 % (okay 3 %), bulk modulus good within 10 % (okay 25 %), thermal expansion good within",
           "20 % (okay 40 %).",
           "",
           "* **reliable**: good on every property that could be graded.",
           "* **usable**: nothing poor, but at least one property only okay.",
           "* **avoid**: poor on the property named (the number is its error), or the model failed outright: it changed",
           "  the crystal into a different form, or predicted an unstable crystal.",
           "* **not graded**: there is nothing to compare with for any property.",
           "* **heat untested**: thermal expansion could not be graded, because there is no measurement to compare with,",
           "  the material is layered, or the model's calculation failed. The reason is in the CSV.",
           "",
           "This is evidence from this benchmark, not a guarantee. It covers perfect bulk crystals and three properties;",
           "check a model on the property you need before relying on it.",
           ""]
    for cls in dict.fromkeys(g["class"]):
        sub = g[g["class"] == cls]
        out += [f"## {class_labels.get(cls, cls)}", "",
                "| material | " + " | ".join(labels.get(m, m) for m in models) + " |",
                "|---|" + "---|" * len(models)]
        for mat in dict.fromkeys(sub["material"]):
            cells = []
            for m in models:
                r = sub[(sub["material"] == mat) & (sub["model"] == m)]
                if r.empty:
                    cells.append("–")
                    continue
                r = r.iloc[0]
                v = r["verdict"]
                if v.startswith("avoid for"):
                    worst = [f"{p[0]} {r[f'{p[0]}: error %']:+.0f} %" for p in PROPS if r[f"{p[0]}: grade"] == "poor"]
                    v = "**avoid**: " + ", ".join(worst) + ("; heat untested" if "heat untested" in r["verdict"] else "")
                elif v.startswith("avoid:"):
                    v = "**avoid**: " + v[len("avoid: "):]
                cells.append(v)
            out.append(f"| {mat} | " + " | ".join(cells) + " |")
        out.append("")
    counts = g.groupby("model")["verdict"].apply(
        lambda s: f"{s.str.startswith('reliable').sum()} reliable, {s.str.startswith('usable').sum()} usable, "
                  f"{s.str.startswith('avoid').sum()} avoid").to_dict()
    out += ["## Summary", "", "| model | verdicts over 33 materials |", "|---|---|"]
    out += [f"| {labels.get(m, m)} | {counts[m]} |" for m in models]
    return "\n".join(out) + "\n"
